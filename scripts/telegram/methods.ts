/** `sendMessage` -> `send_message`, as the Python libraries name the methods. */
export const snake = (name: string): string => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

/** Where a Bot API method is sent: the token is part of the path. */
export const PATH = (method: string): string => `/bot{token}/${method}`;
